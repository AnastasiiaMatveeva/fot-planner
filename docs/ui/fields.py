# -*- coding: utf-8 -*-
"""Смысл граф пакета договора: какие данные нужны и как их подписывают формы.

SOURCE-004. Номер формы и название листа разбор не выбирают: РКМ, структура
цены и расшифровка ФОТ — примеры одних и тех же данных. Что из них нужно,
экономисты выделили в образцах жёлтым: трудоёмкость по должностям с периодами,
ФОТ по этапам, нормативы года, срок договора. Здесь для каждого поля —
подписи, по которым его находит разборщик (`docs/ui/extract.py`). Форма с
теми же данными, но другой раскладкой читается без правки кода; незнакомая
подпись добавляется в перечень, а не в разборщик.
"""
from __future__ import annotations

import re


def norm(text):
    """Подпись для сравнения: без регистра, «ё», пробелов и знаков.

    «Кол-во чел/мес.» и «кол-во  чел./мес» — одна подпись; перенос строки в
    шапке и точка после сокращения на смысл не влияют.
    """
    return re.sub(r"[^0-9a-zа-я]+", "", str(text or "").lower().replace("ё", "е"))


def _table(pairs):
    return tuple((field, tuple(norm(s) for s in syns)) for field, syns in pairs)


#: Таблица трудоёмкости. Побеждает самая длинная совпавшая подпись, при равной
#: длине — поле выше в перечне: «стоимость чел./мес.» не путается с
#: трудоёмкостью, «трудоемкость на 1 чел.» — с «кол-во чел/мес».
LABOR = _table((
    ("position", ("квалификационная группа", "категория работников", "должность")),
    ("headcount", ("количество привлекаемых специалистов", "количество человек",
                   "кол-во человек", "численность")),
    # «Тудоемкость» — опечатка в самом образце структуры цены.
    ("per_person", ("трудоемкость на 1 чел", "тудоемкость на 1 чел", "на 1 чел")),
    ("unit_cost", ("стоимость чел./мес", "стоимость чел.-мес", "стоимость 1 чел",
                   "сумма месячной з/пл", "месячной заработной платы")),
    ("person_months", ("трудоемкость выполнения работ", "кол-во чел/мес",
                       "количество чел/мес", "чел./мес", "чел.-мес", "человеко-месяц")),
    ("total", ("основная заработная плата", "итого фот")),
    ("date_from", ("начало этапа", "дата начала")),
    ("date_to", ("окончание этапа", "дата окончания")),
    ("period", ("срок выполнения",)),
    ("stage", ("наименование этапа", "№ этапа", "номер этапа")),
    ("work_type", ("тип работ", "вид работ")),
))
#: Без этих граф таблица — не трудоёмкость: должность, стоимость и
#: трудоёмкость (всего или на одного человека).
LABOR_REQUIRED = ({"position"}, {"unit_cost"}, {"person_months", "per_person"})

#: Нормативы года: подпись строки, число — в графе «Значение». Частное стоит
#: выше общего: «страховые взносы … от несчастных случаев» — не взносы 30 %.
NORMS = _table((
    ("взносы от несчастных случаев, %", ("несчастных случаев",)),
    ("страховые взносы, %", ("страховые взносы",)),
    ("среднемесячная заработная плата, руб.", ("среднемесячная заработная плата",)),
    ("дополнительная заработная плата ППС, %",
     ("дополнительная заработная плата профессорско",)),
    ("дополнительная заработная плата НИТР, %",
     ("дополнительная заработная плата инженерно", "дополнительная заработная плата научн")),
    ("дополнительная заработная плата, %", ("дополнительная заработная плата",)),
))
NORMS_VALUE = norm("значение")

#: ФОТ по этапам: статьи расходов строками, этапы графами.
PERIOD_COSTS = _table((
    ("основная заработная плата", ("основная заработная плата",)),
    ("дополнительная заработная плата", ("дополнительная заработная плата",)),
    ("обязательные отчисления", ("обязательные отчисления", "отчисления от оплаты труда",
                                 "отчисления на социальные нужды")),
    ("расходы на оплату труда", ("расходы на оплату труда",)),
))
#: Похожие статьи, которые к исполнителям договора не относятся: оплата
#: административно-управленческого аппарата сидит в накладных.
PERIOD_COSTS_EXCLUDE = (norm("административно"), norm("управленческ"))
#: Графа этапа: «Этап 1», «Этап 2, руб.».
STAGE = re.compile(r"^\s*этап\s*(\d+)", re.I)
#: Рядом с графами этапов у таблицы статей стоит итог или название статей.
PERIOD_COSTS_HEAD = (norm("сумма"), norm("всего"), norm("статьи расходов"))

#: Срок договора: пара граф «начало» и «окончание».
TERM_FROM, TERM_TO = norm("начало"), norm("окончание")

#: Строки-итоги и заголовки групп: данными не являются.
TOTAL_MARKS = tuple(norm(s) for s in ("в т.ч", "в том числе", "итого", "всего"))


def best(text, table):
    """Лучшее поле для подписи: (поле, сила совпадения) или None."""
    t = norm(text)
    if not t:
        return None
    found = None
    for rank, (field, syns) in enumerate(table):
        for syn in syns:
            if syn and syn in t and (found is None or (len(syn), -rank) > found[1]):
                found = (field, (len(syn), -rank))
    return found


def header_columns(ws, top, bottom, table, width=40):
    """Графы шапки в строках top..bottom: {поле: (колонка, строка шапки)}.

    Подпись графы бывает в двух-трёх строках: «Трудоемкость и заработная
    плата» над «стоимость чел./мес.». Для графы берётся самая точная из её
    подписей, а поле достаётся графе с самой точной подписью.
    """
    claims = {}
    for c in range(1, min(ws.max_column, width) + 1):
        pick = None
        for r in range(top, bottom + 1):
            v = ws.cell(r, c).value
            if not isinstance(v, str):
                continue
            got = best(v, table)
            if got and (pick is None or got[1] > pick[1]):
                pick = (got[0], got[1], r)
        if pick:
            field, strength, row = pick
            if field not in claims or strength > claims[field][2]:
                claims[field] = (c, row, strength)
    return {f: (c, r) for f, (c, r, _s) in claims.items()}
