def apply_variant(name):
    """Меняет составы на месте; базовый вариант ничего не трогает."""
    if name == "базовый":
        return
    if name == "дефицит":
        INFLOWS["C_BASE-26"] = [950000, 950000, 120000, 120000, 120000] + [400000] * 5 + [850000, 850000]
        c = list(CONTRACTS[0]); c[8] = sum(INFLOWS["C_BASE-26"]); CONTRACTS[0] = tuple(c)
        return
    raise SystemExit("нет такого варианта: %s; есть %s" % (name, ", ".join(VARIANTS)))


#: Кто с какого договора получает зарплату — замысел набора, по которому
#: проверяются деньги. Решатель не обязан следовать ему буква в букву, но
#: если денег не хватает даже на замысел, плана не будет.
def _plan_by_contract():
    """Помесячная раскладка зарплат по договорам — «как задумано»."""
    goz_months = range(3, 11)            # выплаты ГОЗ до 31.10
    grant_months = range(5, 13)          # грант с мая
    bep = 112261.0
    plan = {c[0]: [0.0] * 12 for c in CONTRACTS}
    for m in range(1, 13):
        i = m - 1
        # ГОЗ: четыре ставки, но не выше суммы БЭП по ним.
        goz = (sum(r[2] * r[3] for r in FORM9) / 8.0) if m in goz_months else 0.0
        plan["C_GOZ-26"][i] = goz
        grant = sum(p * s for _, _, p, _, s, _, _ in FOT_DETAIL) / 2.0 if m in grant_months else 0.0
        plan["C_GRANT-26"][i] = grant
        # Коммерция: 124 Сидоровой и Орлову плюс оклад Морозова. У Орлова
        # оклад с надбавкой 122 упирается в П2556 (60 000 на 0,5 ставки),
        # поэтому со 124 остаётся 14 824,45.
        plan["C_COM-26"][i] = 39648.9 + 14824.45 + 47000.0
        # Приоритет: 152 Морозову весь год, оклад с 122 Смирновой до гранта.
        plan["C_PRI-26"][i] = 128000.0 + (100000.0 if m not in grant_months else 0.0)
        # Смирнова до гранта живёт на приоритете, значит внебюджет её не платит.
        need = sum(e[7] for e in EMPLOYEES)
        plan["C_BASE-26"][i] = need - goz - grant - plan["C_COM-26"][i] - plan["C_PRI-26"][i]
    return plan


def check_money():
    """Деньги договора приходят раньше, чем он платит, и ФОТ равен сумме поступлений.

    Проверяется замысел набора (см. `_plan_by_contract`): по каждому договору
    нарастающий итог поступлений не меньше нарастающего итога выплат.
    """
    plan = _plan_by_contract()
    lines, bad = [], False
    for c in CONTRACTS:
        code, fot = c[0], c[8]
        if abs(sum(INFLOWS[code]) - fot) > 0.5:
            lines.append("  %-11s ФОТ %s не равен сумме поступлений %s"
                         % (code, fot, sum(INFLOWS[code])))
            bad = True
        if sum(plan[code]) - fot > 0.5:
            lines.append("  %-11s замысел %.0f больше ФОТ %s" % (code, sum(plan[code]), fot))
            bad = True
        cash = spent = 0.0
        for m in range(1, 13):
            cash += INFLOWS[code][m - 1]
            spent += plan[code][m - 1]
            if spent - cash > 0.5:
                lines.append("  %-11s месяц %2d: выплат %9.0f, поступило %9.0f  <-- не хватает"
                             % (code, m, spent, cash))
                bad = True
        lines.append("  %-11s ФОТ %9.0f, замысел выплат %9.0f, остаток %8.0f"
                     % (code, fot, sum(plan[code]), fot - sum(plan[code])))
    need = sum(e[7] for e in EMPLOYEES)
    for m in range(1, 13):
        got = sum(plan[c[0]][m - 1] for c in CONTRACTS)
        if abs(got - need) > 0.5:
            lines.append("  месяц %2d: замысел %.0f не равен зарплатам %.0f" % (m, got, need))
            bad = True
    return lines, bad


