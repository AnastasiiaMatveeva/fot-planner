def apply_variant(name):
    """Меняет составы на месте; базовый вариант ничего не трогает."""
    global FORM9
    if name == "базовый":
        return
    if name == "совместители":
        EMPLOYEES.append(("E009", "Морозов Максим Михайлович", "Инженер", "Отдел 12", 0.5,
                          "совместительство", "основной", 45000))
        EMPLOYEES.append(("E010", "Лебедева Лидия Львовна", "Младший научный сотрудник",
                          "Лаборатория 3", 0.75, "основное", "аспирант", 60000))
        FORM9 = [(1, "Старший научный сотрудник", 8, 118000), (1, "Ведущий инженер", 8, 110000),
                 (3, "Инженер", 20, 90000)]
        c = list(CONTRACTS[0]); c[8] = 6992000; CONTRACTS[0] = tuple(c)
        g = list(CONTRACTS[2]); g[8] = 3624000; CONTRACTS[2] = tuple(g)
        INFLOWS["C_BASE-26"] = [v + 106000 for v in INFLOWS["C_BASE-26"]]
        INFLOWS["C_GOZ-26"] = [0, 0, 1812000, 0, 0, 1812000, 0, 0, 0, 0, 0, 0]
        return
    if name == "п4":
        # Правило экономистов: надбавка за интенсивность режется ровно по
        # пределу П4 — у кого она есть, тот получает ровно предел на ставку.
        # Значит зарплата такого человека и есть предел П4, а надбавка 124
        # добирает то, что не помещается в предел П2556 по должности.
        # Пределы — из приказа 2556 и справки П4, они лежат в реестре.
        # Поднимать зарплату можно только тем, кто не занят на ГОЗ: там
        # средняя штатная часть ограничена БЭП, и остаток зарплаты
        # исполнителям добирается как раз надбавкой 124.
        p4, staff = 149648.9, {"E006": 120000}
        need = 0.0
        for i, e in enumerate(EMPLOYEES):
            if e[0] not in staff:
                continue
            row = list(e)
            row[7] = round(p4 * e[4], 2)
            EMPLOYEES[i] = tuple(row)
            need += row[7] - staff[e[0]] * e[4]
        # Фонд договора с надбавкой не трогаем: 124 нужна не только тем, у
        # кого зарплата равна пределу, но и исполнителям ГОЗ — им БЭП не даёт
        # получить всю зарплату с самого ГОЗ.
        # Зарплата выросла — в январе и феврале работает только базовый
        # договор, поступлений должно хватать на всех.
        INFLOWS["C_BASE-26"] = [760000, 760000] + [400000] * 8 + [560000, 560000]
        b = list(CONTRACTS[0]); b[8] = sum(INFLOWS["C_BASE-26"]); CONTRACTS[0] = tuple(b)
        return
    if name == "дефицит":
        INFLOWS["C_BASE-26"] = [700000, 700000, 120000, 120000, 120000] + [400000] * 5 + [560000, 560000]
        c = list(CONTRACTS[0]); c[8] = sum(INFLOWS["C_BASE-26"]); CONTRACTS[0] = tuple(c)
        return
    raise SystemExit("нет такого варианта: %s; есть %s" % (name, ", ".join(VARIANTS)))


def _bold(ws, row, cols):
    for c in range(1, cols + 1):
        ws.cell(row, c).font = Font(bold=True)


