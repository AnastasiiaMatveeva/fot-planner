def price():
    wb = openpyxl.load_workbook(os.path.join(FORMS, "Структура цены_ОБРАЗЕЦ_расширенный.xlsx"))
    ws = wb["Расшифровка ФОТ"]
    ws["B3"] = ("на выполнение научно-исследовательской работы по гранту РНФ 26-71-10042, "
                "шифр C_GRANT-26")
    # Образец содержит строки-заготовки должностей и объединённые ячейки
    # итогов: расклеиваем область данных, чистим и пишем свои строки.
    for rng in list(ws.merged_cells.ranges):
        if rng.min_row >= 7:
            ws.unmerge_cells(str(rng))
    for r in range(7, ws.max_row + 1):
        for c in range(1, 12):
            ws.cell(r, c).value = None
    r = 7
    n = 1
    for stage, pos, people, months, sal, d1, d2 in FOT_DETAIL:
        ws.cell(r, 1).value = n
        ws.cell(r, 2).value = stage
        ws.cell(r, 3).value = "НИР по гранту"
        ws.cell(r, 4).value = pos
        ws.cell(r, 5).value = people
        ws.cell(r, 6).value = months
        ws.cell(r, 7).value = people * months
        ws.cell(r, 8).value = sal
        ws.cell(r, 9).value = people * months * sal
        ws.cell(r, 10).value = d1
        ws.cell(r, 11).value = d2
        r += 1
        n += 1
    ws.cell(r, 2).value = "ИТОГО:"
    ws.cell(r, 7).value = sum(p * m for _, _, p, m, _, _, _ in FOT_DETAIL)
    ws.cell(r, 9).value = sum(p * m * s for _, _, p, m, s, _, _ in FOT_DETAIL)
    wp = wb["Структура цены"]
    ozp = sum(p * m * s for _, _, p, m, s, _, _ in FOT_DETAIL)
    st1 = sum(p * m * s for st, _, p, m, s, _, _ in FOT_DETAIL if st == "Этап 1")
    wp["D8"], wp["E8"], wp["F8"] = ozp, st1, ozp - st1
    wp["D9"], wp["E9"], wp["F9"] = round(ozp * 0.086866), round(st1 * 0.086866), round((ozp - st1) * 0.086866)
    wp["D10"] = round((ozp + ozp * 0.086866) * 0.302)
    wp["D7"] = ozp + wp["D9"].value
    return wb


def main():
    import argparse
    ap = argparse.ArgumentParser()
    ap.add_argument("--variant", default="базовый", help=", ".join(VARIANTS))
    ap.add_argument("--out", default=OUT, help="куда писать файлы (по умолчанию data/demo)")
    args = ap.parse_args()
    apply_variant(args.variant)
    out = args.out
    os.makedirs(out, exist_ok=True)
    files = {
        "Штатное расписание 2026.xlsx": staff(),
        "Договоры 2026.xlsx": contracts(),
        "РКМ ГОЗ Радар-26.xlsx": rkm(),
        "Структура цены Грант-26.xlsx": price(),
    }
    for name, wb in files.items():
        path = os.path.join(out, name)
        wb.save(path)
        print("записан", path)
    total = sum(e[7] for e in EMPLOYEES)
    print("зарплат в месяц: %s; денег за год: %s"
          % ("{:,.0f}".format(total).replace(",", " "),
             "{:,.0f}".format(sum(sum(v) for v in INFLOWS.values())).replace(",", " ")))


if __name__ == "__main__":
    sys.exit(main())
