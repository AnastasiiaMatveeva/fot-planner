    ws["C12"] = "Дата заключения договора - 01.03.2026"
    ws["C13"] = "01.03.2026 - 31.12.2026"
    total_cm = sum(r[2] for r in FORM9)
    total_ozp = sum(r[2] * r[3] for r in FORM9)
