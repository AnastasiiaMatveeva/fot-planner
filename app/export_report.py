    # 10. Трудоёмкость по строкам РКМ за год.
    heads = ["Договор", "Строка РКМ", "Трудоёмкость по РКМ за год, чел.-мес.",
             "Закрыто исполнителями за год, чел.-мес.", "Отклонение трудоёмкости, чел.-мес.",
             "Отклонение трудоёмкости, %", "Стоимость трудоёмкости по РКМ за год, ₽",
             "Выплаты исполнителям за год, ₽", "Отклонение стоимости, ₽", "Отклонение стоимости, %",
             "Средняя стоимость 1 чел.-мес. по РКМ, ₽", "Средняя стоимость 1 чел.-мес. по плану, ₽",
             "Отклонение средней стоимости, ₽", "Отклонение средней стоимости, %",
             "Число исполнителей по РКМ, чел.", "Число исполнителей в месяц, наибольшее, чел.",
             "Состояние"]
    rows = [[x["договор"], x["строка"], x["план чел-мес"], x["факт чел-мес"], x["д чел-мес"],
             _pct(x.get("д чел-мес %")), x["план сумма"], x["факт сумма"], x["д сумма"],
             _pct(x.get("д сумма %")), x["средняя план"], x["средняя факт"], x["д средней"],
             _pct(x.get("д средней %")), x["людей предел"], x["людей макс"], x["статус"]]
            for x in rep["трудоемкость"]]
    _sheet(wb, SHEETS["10"], heads, rows,
           formats={2: _RATE, 3: _RATE, 4: _RATE, 5: _PCT, 6: _MONEY, 7: _MONEY, 8: _MONEY, 9: _PCT,
                    10: _MONEY, 11: _MONEY, 12: _MONEY, 13: _PCT}, freeze=2)

    # 11. Распределение трудоёмкости строк РКМ по исполнителям помесячно,
    # чел.-мес. — одна величина на листе; деньги строк — в разделе 10.
    heads = (["Договор", "Строка РКМ", "Исполнитель", "Должность исполнителя"] + _months_head(fact_to)
             + ["За год, чел.-мес."])
    rows = []
    for w in rep["кто"]:
        rows.append([w["договор"], w["строка"], "План по РКМ", None]
                    + (w["план по месяцам"] or [None] * 12) + [w["план"]])
        rows.append([w["договор"], w["строка"], "Закрыто исполнителями", None]
                    + w["закрыто"] + [w["закрыто год"]])
        rows.append([w["договор"], w["строка"], "Отклонение от плана", None]
                    + w["отклонение"] + [w["отклонение год"]])
        for p in w["люди"]:
            rows.append([w["договор"], w["строка"], p["фио"], p["должность"]]
                        + p["ставка"] + [p["ставка год"]])
    _sheet(wb, SHEETS["11"], heads, rows, formats={i: _RATE for i in range(4, 17)}, freeze=4)

    # 12. Незакрытая трудоёмкость по строкам РКМ, чел.-мес.
    heads = ["Договор", "Строка РКМ", "Трудоёмкость по РКМ, чел.-мес.",
             "Закрыто исполнителями, чел.-мес.", "Не закрыто, чел.-мес.",
             "Месяцев выполнения работ", "Требуется дополнительно ставок в месяц"]
    rows = [[g["договор"], g["строка"], g["по РКМ"], g["закрыто"], g["не закрыто"], g["месяцев"],
             g["ставок в месяц"]] for g in rep["незакрыто"]]
    if rows:
        rows.append(["Итого не закрыто, чел.-мес.", None, None, None,
                     round(sum(g["не закрыто"] or 0 for g in rep["незакрыто"]), 2), None, None])
    _sheet(wb, SHEETS["12"], heads, rows, formats={2: _RATE, 3: _RATE, 4: _RATE, 6: _RATE})

    # 13.1 Версии расчёта; 13.2 Целевые показатели и параметры расчёта.
    # Целевые показатели других версий выгрузке не передаются — версии
    # листом без них, показатели этой версии — в 13.2.
    rows = [[v.get("номер"), "Рассчитан" if v.get("статус") == "OPTIMAL" else v.get("статус"),
             v.get("секунд"), v.get("дата")] for v in versions or []]
    _sheet(wb, SHEETS["13.1"], ["Версия расчёта", "Состояние", "Время расчёта, с", "Дата расчёта"],
           rows, widths={0: 12, 1: 22, 2: 14, 3: 20})
    rows = []
    for g in goals or []:
        if g.get("приоритет") != "вес":
            continue
        rows.append([g.get("цель"), g.get("значение"), g.get("единица"), g.get("вес")])
    for st in rep["настройки"]:
        value = st["значение"]
        if st.get("единица") == "%" and isinstance(value, (int, float)):
            value = round(value * 100, 2)
        rows.append([st.get("название") or st["имя"], value, st.get("единица"), None])
    _sheet(wb, SHEETS["13.2"], ["Целевой показатель или параметр", "Значение", "Единица измерения",
                                "Вес в целевой функции"], rows, widths={0: 48})
    try:
        import reference
        rows = [[field, x.get("документ"), x.get("основание"),
                 x.get("действует с") or x.get("загружен")]
                for field, x in reference.read_sources().items()]
        _sheet(wb, SHEETS["13.3"], ["Величина справочника", "Документ", "Основание", "Действует с"],
               rows, widths={0: 24, 1: 40, 2: 40})
    except Exception:  # noqa: BLE001 — источники не обязательны для выгрузки
        pass

    # 14. Недоплата заработной платы сотрудникам по месяцам, ₽.
    heads = ["Табельный номер", "ФИО", "Месяц", "Заработная плата за месяц, ₽",
             "Выплаты по плану, ₽", "Недоплата, ₽", "Причина"]
    rows = [[d["табельный"], d["фио"], _mon(d["месяц"]), d["положено"], d["выплачено"], d["дефицит"],
             d["причина"]] for d in rep["дефицит"]]
    _sheet(wb, SHEETS["14"], heads, rows, formats={3: _MONEY, 4: _MONEY, 5: _MONEY})

    # 15. Протокол контроля плана ФОТ: условие названо формально
    # (rules.TITLES), ключ «правило» остаётся для матрицы проверок.
    heads = ["Группа условий", "Условие", "Тип условия", "Состояние", "Итог проверки",
             "Проверено случаев", "Нарушений", "Наибольшая доля предела", "Где смотреть",
             "Содержание условия"]
    rows = [[c["раздел"], c.get("название") or c["правило"], c["тип"], c["состояние"], c["факт"],
             c["проверено"], c["нарушений"], _pct(c.get("использовано")), c["где"], c["смысл"]]
            for c in checks]
    ws = _sheet(wb, SHEETS["15"], heads, rows, formats={7: _PCT}, widths={1: 44, 4: 60, 9: 70})
    for r in range(2, ws.max_row + 1):
        for c in (5, 10):
            ws.cell(r, c).alignment = Alignment(wrap_text=True, vertical="top")

    # 16. ФОТ по управленческим подразделениям помесячно, ₽ (01.10.2026):
    # подразделение — графой, как велит UI-022; строка итога подразделения.
    pd = rep.get("по подразделениям") or {"подразделения": [], "итого": [None] * 12, "год": 0}
    month_heads = [_mon(m) for m in range(1, 13)]
    heads = ["Управленческое подразделение", "Табельный номер", "ФИО"] + month_heads + ["За год, ₽"]
    rows = []
    for d in pd["подразделения"]:
        for person in d["люди"]:
            rows.append([d["подразделение"], person["табельный"], person["фио"]]
                        + list(person["месяцы"]) + [person["год"]])
        rows.append([d["подразделение"], "Итого по подразделению", None] + list(d["месяцы"])
                    + [d["год"]])
    if pd["подразделения"]:
        rows.append(["Итого по организации", None, None] + list(pd["итого"]) + [pd["год"]])
    _sheet(wb, SHEETS["16"], heads, rows, formats={i: _MONEY for i in range(3, 16)},
           widths={0: 36, 2: 30})

    # Листы решателя — в конец, как основание расчёта.
    for name in solver_sheets:
        wb.move_sheet(name, offset=len(wb.sheetnames))
    wb.active = 0
    wb.save(out_path)
    return out_path
