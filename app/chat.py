    stop = {"когда", "какой", "какая", "какие", "есть", "этот", "документ",
            "файл", "тут", "там", "страница", "листе", "почему", "ответ"}
    words = {w for w in re.findall(r"[а-яёa-z0-9]{4,}", (query or "").lower())
             if w not in stop}
    # Эти слова помогают перепроверять временные ограничения даже при коротком
    # вопросе «а даты?», но не заменяют слова самого экономиста.
    audit = ("дата", "договор", "подписан", "заключен", "заключён", "этап",
             "период", "начало", "окончание", "срок", "месяц", "трудоем",
             "трудоём")
    has_time_question = any(root in (query or "").lower() for root in audit)
    scored = []
    for i, line in enumerate(lines):
        low = line.lower()
        score = sum(5 for w in words if w in low)
        if has_time_question:
            score += sum(2 for root in audit if root in low)
            if re.search(r"\b\d{2}[./]\d{2}[./]20\d{2}\b", line):
                score += 6
        if score:
            scored.append((score, i))
    if not scored:
        scored = [(1, i) for i in range(min(80, len(lines)))]

    chosen = set()
    headings = []
    for i, line in enumerate(lines):
        if line.startswith("### "):
            headings.append(i)
    for _, i in sorted(scored, reverse=True)[:50]:
        chosen.update(range(max(0, i - 1), min(len(lines), i + 2)))
        previous = [h for h in headings if h <= i]
        if previous:
            chosen.add(previous[-1])
    out = []
    total = 0
    for i in sorted(chosen):
        line = lines[i]
        if total + len(line) + 1 > limit:
            break
        out.append(line)
        total += len(line) + 1
    return "\n".join(out)


