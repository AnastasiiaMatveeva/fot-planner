_MON = ["январь", "февраль", "март", "апрель", "май", "июнь", "июль", "август",
        "сентябрь", "октябрь", "ноябрь", "декабрь"]


def _labor_months_text(raw):
    """План по месяцам словами: «июнь–сентябрь по 1,0; октябрь–декабрь по 1,0»."""
    import json as _json

    try:
        months = {int(k): float(v) for k, v in (_json.loads(raw) or {}).items()}
    except (ValueError, TypeError, AttributeError):
        return str(raw)
    runs, start, prev, val = [], None, None, None
    for m in range(1, 14):
        v = months.get(m)
        if v is not None and v == val and prev == m - 1:
            prev = m
            continue
        if start is not None:
            runs.append((start, prev, val))
        start, prev, val = (m, m, v) if v is not None else (None, None, None)
    return "; ".join(
        ("%s по %s" % (_MON[a - 1], ("%g" % v).replace(".", ",")) if a == b
         else "%s–%s по %s" % (_MON[a - 1], _MON[b - 1], ("%g" % v).replace(".", ",")))
        for a, b, v in runs)


