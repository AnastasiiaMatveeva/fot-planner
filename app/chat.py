def _norms_facts(db, doc):
    """Чем закончился разбор нормативного документа.

    Без этого модель в разговоре о приказе отвечала наугад — «таблица не
    распознана, переразберите как штатное расписание», хотя величины
    извлечены и сверены со справочником. Здесь ровно то, что сделал
    разборщик: правило выбора колонки, какие величины ушли в справочник,
    какие строки не сошлись и что ждёт подтверждения.
    """
    import json as _json

    from db import Message

    if not getattr(doc, "gave", None):
        return []
    try:
        gave = _json.loads(doc.gave)
    except ValueError:
        return []
    if not isinstance(gave, dict) or "величин" not in gave:
        return []
    out = ["Это нормативный документ: строк реестра он не даёт, он задаёт "
           "величины справочнику должностей (графы «оклад», «П2556», «П4»). "
           "Разобран (%s), вид определён верно, переразбирать его не нужно."
           % (doc.parsed_by or "разборщиком")]
    out.append("Правило разбора: справочник хранит предельный уровень по "
               "должности, поэтому если в таблице несколько колонок по "
               "внутридолжностным категориям (без категории, II, I), берётся "
               "наибольшая — последняя колонка; значения других колонок в "
               "справочник не идут.")
    out.append("Извлечено величин: %s; сошлось со справочником строк: %s; "
               "расхождений: %s."
               % (gave.get("величин"), len(gave.get("строки") or []),
                  gave.get("расхождений")))
    for row in (gave.get("строки") or [])[:20]:
        out.append("  из строки «%s» взято: %s"
                   % (str(row.get("строка"))[:160],
                      ", ".join(row.get("значения") or [])))
    miss = gave.get("вне справочника") or []
    if miss:
        out.append("Строки документа, для которых в справочнике нет должности "
                   "(их величины никуда не ушли — сначала нужно завести "
                   "должность в справочнике):")
        for m in miss[:10]:
            if isinstance(m, dict):
                out.append("  «%s» — величина %s"
                           % (str(m.get("строка"))[:160],
                              ", ".join(m.get("значения") or [])))
            else:
                out.append("  «%s»" % str(m)[:160])
    for m in (db.query(Message).filter_by(document_id=doc.id)
              .order_by(Message.id.desc()).limit(30).all()):
        try:
            pl = _json.loads(m.payload) if m.payload else None
        except ValueError:
            pl = None
        if isinstance(pl, dict) and pl.get("kind") == "reference_diff":
            out.append("Ждут подтверждения расхождения со справочником: "
                       + "; ".join("%s, %s: %s → %s"
                                   % (c.get("pos"), c.get("field"),
                                      c.get("old"), c.get("new"))
                                   for c in (pl.get("changes") or [])[:10]))
            break
    return out


def doc_history(db, doc, limit=10):
    from db import Message
    msgs = list(reversed(db.query(Message).filter_by(document_id=doc.id)
                         .order_by(Message.id.desc()).limit(limit).all()))
    # После перечитывания документа прежние ответы устарели, а модель охотно
    # повторяет свою же реплику из истории. Оставляем только то, что после
    # последнего «Разобрал …» / «Сверил …».
    cut = 0
    for i, m in enumerate(msgs):
        if m.who != "экономист" and str(m.text or "").startswith(("Разобрал «", "Сверил «")):
            cut = i + 1
    msgs = msgs[cut:]
    return "\n".join("%s: %s" % ("Экономист" if m.who == "экономист" else "Агент", m.text)
                      for m in msgs)


